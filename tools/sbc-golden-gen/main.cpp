// Runs FFmpeg's own SBC encoder and the copy in third_party/sbc side by side over
// the same sounds, and says whether a single byte differs.
//
//   sbc-golden-gen [frames]              compare, frames per setting and signal
//   sbc-golden-gen --write <file>        write tests/sbc_encoder_golden.inl
//
// ⭐ WHY IT IS KEPT WHEN FFMPEG IS GONE. tests/sbc_encoder_golden.inl is what FFmpeg
// produced, and this is the only thing that can make it again. It needs FFmpeg 8.0's
// headers and libraries, which this repo's history still holds: the parent of
// `git log -1 --format=%h -- third_party/ffmpeg` has them. Check that out beside this
// tree and run build.bat with FFMPEG_ROOT at its third_party\ffmpeg\x64\release.

#include "ffmpeg_side.h"
#include "sbc_test_signals.h"

#include "sbc/sbc_encoder.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>

using namespace sbctest;

namespace {

struct RunResult {
    uint64_t frames = 0;
    uint64_t hash = kHashStart;
    long long firstDifference = -1;
    int firstDifferentByte = -1;
    uint64_t differentFrames = 0;
};

RunResult run(const Settings &settings, int which, uint64_t frames)
{
    RunResult result;
    Signal signal(which, settings.sampleRate);
    FfmpegEncoder *theirs = ffmpeg_encoder_create(settings);
    SbcEncoder *ours = sbc_encoder_create(settings.frequency, settings.blocks, settings.mode,
                                          settings.allocation, settings.subbands, settings.bitpool);
    if (theirs == nullptr || ours == nullptr) {
        std::fprintf(stderr, "could not start the encoders for %s\n", settings.name);
        std::exit(2);
    }

    const size_t samples = static_cast<size_t>(settings.subbands) * settings.blocks;
    std::vector<int16_t> pcm(samples * 2);
    std::vector<uint8_t> theirBytes(4096);
    std::vector<uint8_t> ourBytes(4096);
    for (uint64_t frame = 0; frame < frames; ++frame) {
        for (size_t i = 0; i < samples; ++i) {
            signal.next(&pcm[i * 2], &pcm[i * 2 + 1]);
        }
        const int theirSize = ffmpeg_encoder_encode(theirs, pcm.data(), theirBytes.data(), theirBytes.size());
        const int ourSize = sbc_encoder_encode(ours, pcm.data(), ourBytes.data(), ourBytes.size());
        if (theirSize <= 0 || ourSize <= 0) {
            std::fprintf(stderr, "an encoder failed: theirs %d, ours %d, %s\n", theirSize, ourSize, settings.name);
            std::exit(2);
        }
        result.hash = hash_more(result.hash, theirBytes.data(), static_cast<size_t>(theirSize));
        result.frames++;
        if (theirSize != ourSize || std::memcmp(theirBytes.data(), ourBytes.data(), static_cast<size_t>(ourSize)) != 0) {
            result.differentFrames++;
            if (result.firstDifference < 0) {
                result.firstDifference = static_cast<long long>(frame);
                for (int at = 0; at < theirSize && at < ourSize; ++at) {
                    if (theirBytes[static_cast<size_t>(at)] != ourBytes[static_cast<size_t>(at)]) {
                        result.firstDifferentByte = at;
                        break;
                    }
                }
            }
        }
    }
    ffmpeg_encoder_destroy(theirs);
    sbc_encoder_destroy(ours);
    return result;
}

}  // namespace

int main(int argc, char **argv)
{
    if (argc == 3 && std::strcmp(argv[1], "--write") == 0) {
        FILE *out = nullptr;
        if (fopen_s(&out, argv[2], "wb") != 0 || out == nullptr) {
            std::fprintf(stderr, "cannot write %s\n", argv[2]);
            return 2;
        }
        std::fprintf(out, "// GENERATED by tools/sbc-golden-gen from FFmpeg 8.0's own SBC encoder. Do not edit.\n");
        std::fprintf(out, "// One line per setting and signal: their positions in sbc_test_signals.h, and a\n");
        std::fprintf(out, "// hash of every byte FFmpeg produced for kFramesPerRun frames.\n");
        for (int s = 0; s < kSettingsCount; ++s) {
            for (int w = 0; w < kSignalCount; ++w) {
                const RunResult result = run(kSettings[s], w, kFramesPerRun);
                if (result.differentFrames != 0) {
                    std::fprintf(stderr, "%s, %s: the two differ, nothing to write\n", kSettings[s].name, kSignalNames[w]);
                    std::fclose(out);
                    return 1;
                }
                std::fprintf(out, "{%d, %d, 0x%016llxULL},\n", s, w, static_cast<unsigned long long>(result.hash));
            }
        }
        std::fclose(out);
        return 0;
    }

    const uint64_t frames = argc == 2 ? std::strtoull(argv[1], nullptr, 10) : kFramesPerRun;
    uint64_t total = 0;
    uint64_t totalDifferent = 0;
    for (int s = 0; s < kSettingsCount; ++s) {
        for (int w = 0; w < kSignalCount; ++w) {
            const RunResult result = run(kSettings[s], w, frames);
            total += result.frames;
            totalDifferent += result.differentFrames;
            std::printf("%-18s %-28s %10llu frames, %s", kSettings[s].name, kSignalNames[w],
                        static_cast<unsigned long long>(result.frames),
                        result.differentFrames == 0 ? "identical" : "DIFFERENT");
            if (result.differentFrames != 0) {
                std::printf(": %llu frames, first at frame %lld byte %d",
                            static_cast<unsigned long long>(result.differentFrames),
                            result.firstDifference, result.firstDifferentByte);
            }
            std::printf("\n");
        }
    }
    std::printf("%llu frames, %llu different\n", static_cast<unsigned long long>(total),
                static_cast<unsigned long long>(totalDifferent));
    return totalDifferent == 0 ? 0 : 1;
}
